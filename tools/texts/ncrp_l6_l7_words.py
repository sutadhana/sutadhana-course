MISSING = []


def build_texts():
    import re
    tok = re.compile(r"[^\s,.;:!?“”\"‘()…*—–]+(?:\([^\s()]+\))?")
    out = []
    for tid, ref, title, title_en, source, credit, paras in META:
        local = T.get(tid, {})
        words = {}

        def find(k):
            return local.get(k) or C.get(k) or C13.get(k)

        for pa, _ in paras:
            pa = re.sub(r"ṃ pi(?=[\s,.;:!?”’…—–]|$)", "mpi", pa)
            for w in tok.findall(pa):
                k = w.lower()
                if k in words:
                    continue
                if find(k):
                    words[k] = find(k)
                elif k.endswith("mpi"):
                    # built from the two words by the library builder
                    base = k[:-3] + "ṃ"
                    if not find(base):
                        raise SystemExit(f"{tid}: no analysis for {base!r} (in {k!r})")
                    words[base] = find(base)
                    if find("pi"):
                        words["pi"] = find("pi")
                else:
                    MISSING.append((tid, k))
        out.append(dict(id=tid, ref=ref, title=title, titleEn=title_en, source=source, credit=credit,
                        paras=paras, words=copy.deepcopy(words)))
    return out


TEXTS = build_texts()
if MISSING:
    raise SystemExit(f"no analysis for: {MISSING}")
