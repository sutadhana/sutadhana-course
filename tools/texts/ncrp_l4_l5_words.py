NASAL = "The ṃ becomes n and the apostrophe joins it to ti (iti), which closes the quotation."
IVA = "iva (like, as) loses its first i and joins the word before it: ’va."


def ITI(form1, l, g, meaning, ctx, role=None, nasal=False, lengthen=False, what="closes the quotation"):
    """word + iti written together: …’ti"""
    if nasal:
        note = f"{form1} + iti: the ṃ becomes n and iti loses its first i."
    elif lengthen:
        note = "The final vowel is lengthened before iti, which loses its first i."
    else:
        note = "iti loses its first i and joins with an apostrophe."
    return M(f"{form1} + iti", "sandhi", ctx, role=role,
             parts=[(form1, l, g, meaning), ("iti", "iti", "ind", what)], note=note)


