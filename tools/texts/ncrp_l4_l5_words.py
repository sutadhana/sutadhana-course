def build_texts():
    import re
    tok = re.compile(r"[^\s,.;:!?“”\"‘()…*—–]+(?:\([^\s()]+\))?")
    out = []
    for tid, ref, title, title_en, source, credit, paras in META:
        local = T.get(tid, {})
        words = {}
        for pa, _ in paras:
            pa = re.sub(r"ṃ pi(?=[\s,.;:!?”’…—–]|$)", "mpi", pa)
            for w in tok.findall(pa):
                k = w.lower()
                if k in words:
                    continue
                if k in local:
                    words[k] = local[k]
                elif k in C:
                    words[k] = C[k]
                elif k.endswith("mpi"):
                    continue  # built from the two words by the library builder
                else:
                    raise SystemExit(f"{tid}: no analysis for {k!r}")
        out.append(dict(id=tid, ref=ref, title=title, titleEn=title_en, source=source, credit=credit,
                        paras=paras, words=words))
    return out


TEXTS = build_texts()
